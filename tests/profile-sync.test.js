'use strict';
const assert=require('node:assert/strict');
const Sync=require('../js/profile-sync');
const clone=x=>JSON.parse(JSON.stringify(x));
const base={name:'Conta',training:{threat:{attempts:0,correct:0,hints:0}},gameArchive:[],weaknessSession:null};
const seed=Sync.stamp(base,base,'seed','2026-11-13T10:00:00Z');
let a=clone(seed);a.training.threat.attempts=1;a=Sync.stamp(a,seed,'PC','2026-11-13T10:01:00Z');
let b=clone(seed);b.training.threat.attempts=2;b=Sync.stamp(b,seed,'phone','2026-11-13T10:02:00Z');
const combined=Sync.merge(a,b);
assert.equal(combined.training.threat.attempts,3);
assert.ok(Sync.equivalent(Sync.merge(a,b),Sync.merge(b,a)));
assert.ok(Sync.equivalent(Sync.merge(combined,b),combined));
const move={fenBefore:'fen',uci:'e2e4'};
const remote={...clone(base),gameArchive:[{id:'remote',moves:[move],pgn:'1. e4 *',analysis:{userColor:'w',phaseEngine:{moves:[{ply:1,best:'e2e4'}]}}}],training:{threat:{attempts:5,correct:2,hints:0}}};
const guest={...clone(base),name:'Convidado',gameArchive:[{id:'duplicate',moves:[move],pgn:'1. e4 *',analysis:{userColor:'w'}},{id:'new',moves:[{fenBefore:'other',uci:'d2d4'}],pgn:'1. d4 *',analysis:{userColor:'w'}}],training:{threat:{attempts:2,correct:1,hints:1}},weaknessSession:{index:0,hint:1,items:[{archiveId:'duplicate'}]}};
const before=JSON.stringify(guest);
const migrated=Sync.transferGuest(remote,guest,'browser1');
assert.equal(migrated.gameArchive.length,2);
assert.equal(migrated.name,'Conta');
assert.equal(migrated.training.threat.attempts,7);
assert.equal(migrated.gameArchive[0].analysis.phaseEngine.moves.length,1);
assert.equal(migrated.weaknessSession.hint,1);
assert.equal(migrated.weaknessSession.items[0].archiveId,'remote');
assert.ok(Sync.equivalent(Sync.transferGuest(migrated,guest,'browser1'),migrated));
assert.equal(JSON.stringify(guest),before);
let finished=clone(migrated);finished.weaknessSession=null;finished=Sync.stamp(finished,migrated,'phone','2026-12-01T10:00:00Z');
assert.equal(Sync.merge(migrated,finished).weaknessSession,null);
assert.equal(Sync.merge(finished,migrated).weaknessSession,null);
assert.equal(Sync.transferGuest(finished,guest,'browser1').weaknessSession,null);
const updated=clone(migrated);updated.gameArchive[0].analysis.engineReview={checkedAt:'new',items:[{ply:1}]};
const stamped=Sync.stamp(updated,migrated,'phone','2026-12-02T10:00:00Z');
assert.equal(Sync.merge(migrated,stamped).gameArchive[0].analysis.engineReview.items.length,1);
const lots={gameArchive:Array.from({length:125},(_,i)=>({id:`g${i}`,moves:[{fenBefore:String(i),uci:'e2e4'}]}))};
assert.equal(Sync.merge(lots,{}).gameArchive.length,125);
assert.equal(Sync.hasProgress(base),false);
assert.equal(Sync.hasProgress(guest),true);
assert.ok(Sync.equivalent({a:1,b:{c:2,d:3}},{b:{d:3,c:2},a:1}));
console.log('✓ Sincronização: concorrência, idempotência, transferência, diagnósticos, sessões e histórico sem corte.');
